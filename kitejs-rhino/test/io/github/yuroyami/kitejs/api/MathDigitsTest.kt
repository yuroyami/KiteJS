        val script = """
            var view = new DataView(new ArrayBuffer(8));
            function fromHex(h) {
                view.setUint32(0, parseInt(h.slice(0, 8), 16));
                view.setUint32(4, parseInt(h.slice(8), 16));
                return view.getFloat64(0);
            }
            function toHex(x) {
                view.setFloat64(0, x);
                return ('0000000' + view.getUint32(0).toString(16)).slice(-8) +
                    ('0000000' + view.getUint32(4).toString(16)).slice(-8);
            }
            var wrong = [];
            VECTORS.forEach(function (line) {
                var p = line.split(' ');
                var f = Math[p[0]];
                var answer = p.length == 3 ? f(fromHex(p[1])) : f(fromHex(p[1]), fromHex(p[2]));
                var want = p[p.length - 1];
                var bothNaN = answer !== answer && fromHex(want) !== fromHex(want);
                if (!bothNaN && toHex(answer) != want) wrong.push(line + ' got ' + toHex(answer));
            });
            wrong.join('\n');
        """.trimIndent().replace("VECTORS", vectors.joinToString(",", "[", "]") { "'$it'" })
