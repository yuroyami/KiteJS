/*
 * Writes what V8's Number::toString prints for a set of doubles, as the bits of each and its text:
 *
 *   node tools/dtoa/generate-v8-number-strings.mjs .
 *
 * Every subnormal up to 300 times MIN_VALUE, where Schubfach's two-digit minimum can stand in the
 * way of the shortest form, then random subnormals and random doubles over the whole range.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2] ?? ".";
let seed = 0x0d70a110;
function random32() {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return (t ^ (t >>> 14)) >>> 0;
}
const view = new DataView(new ArrayBuffer(8));
const bitsOf = (d) => { view.setFloat64(0, d); return view.getBigUint64(0); };
const fromBits = (b) => { view.setBigUint64(0, b); return view.getFloat64(0); };

const values = [];
for (let t = 1n; t <= 300n; t++) values.push(fromBits(t));
for (let i = 0; i < 300; i++) values.push(fromBits(BigInt(random32()) | (BigInt(random32() & 0xfffff) << 32n)));
while (values.length < 900) {
    const d = fromBits((BigInt(random32()) << 32n) | BigInt(random32()));
    if (Number.isFinite(d)) values.push(d);
}
const lines = values.map((d) => bitsOf(d).toString(16) + " " + String(d));

const chunks = [];
for (let i = 0; i < lines.length; i += 150) chunks.push('    "' + lines.slice(i, i + 150).join("\\n") + '\\n"');

writeFileSync(join(root, "kitejs-api/src/commonTest/kotlin/io/github/yuroyami/kitejs/api/dtoa/V8NumberStrings.kt"), `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

package io.github.yuroyami.kitejs.api.dtoa

/* Generated by tools/dtoa/generate-v8-number-strings.mjs on V8 ${process.versions.v8}. Do not edit by hand. */

/** The bits of a double, in hexadecimal, and what V8's Number::toString prints for it, one a line. */
internal val V8_NUMBER_STRINGS: List<String> = listOf(
${chunks.join(",\n")},
)
`);
console.log(lines.length + " values");
