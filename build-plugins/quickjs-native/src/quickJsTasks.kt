/** A desktop platform of the JVM jar: its resource folder, its zig target and the library's file name. */
private class JniPlatform(val folder: String, val zigTarget: String, val fileName: String)

private val jniPlatforms = listOf(
    JniPlatform("linux-x86_64", "x86_64-linux-gnu.2.17", "libkitejs_quickjs.so"),
    JniPlatform("linux-aarch64", "aarch64-linux-gnu.2.17", "libkitejs_quickjs.so"),
    JniPlatform("macos-x86_64", "x86_64-macos", "libkitejs_quickjs.dylib"),
    JniPlatform("macos-aarch64", "aarch64-macos", "libkitejs_quickjs.dylib"),
    JniPlatform("windows-x86_64", "x86_64-windows-gnu", "kitejs_quickjs.dll"),
)

/**
 * Builds the JNI library for every desktop platform with `zig cc`, laid out as the jar's resources:
 * `jni/<os>-<arch>/<library>`. The loader in src@jni picks the one for the machine it runs on.
 */
@OptIn(kotlin.io.path.ExperimentalPathApi::class)
@TaskAction
fun buildJniLibraries(
    @Input nativeDir: Path,
    @Output outputDir: Path,
) = buildJni(nativeDir, outputDir, jniPlatforms)

/** Builds the JNI library for the machine the build runs on, in the same layout as [buildJniLibraries]. */
@OptIn(kotlin.io.path.ExperimentalPathApi::class)
@TaskAction
fun buildHostJniLibrary(
    @Input nativeDir: Path,
    @Output outputDir: Path,
) {
    val os = when {
        hostOs.startsWith("mac") -> "macos"
        isWindows -> "windows"
        else -> "linux"
    }
    buildJni(nativeDir, outputDir, jniPlatforms.filter { it.folder == "$os-$hostArch" })
}

@OptIn(kotlin.io.path.ExperimentalPathApi::class)
private fun buildJni(nativeDir: Path, outputDir: Path, platforms: List<JniPlatform>) {
    val include = jdkInclude()
    outputDir.deleteRecursively()
    parallel(platforms.map { platform ->
        {
            val dir = outputDir.resolve("jni/${platform.folder}").createDirectories()
            val library = dir.resolve(platform.fileName)
            run(
                listOf(zig(), "cc", "-target", platform.zigTarget, "-g0", "-s", "-o", library.toString()) +
                    listOf("-shared", "-fPIC", "-fvisibility=hidden") + commonFlags(nativeDir) +
                    listOf("-I$include", "-I${nativeDir.resolve("jni/include")}", "-I$nativeDir") +
                    (if (platform.folder.startsWith("linux")) listOf("-lm") else emptyList()) +
                    (engineSources + "jni/kitejs_quickjs_jni.c").map { nativeDir.resolve(it).toString() },
            )
            // zig leaves an import library and debug data next to a DLL. Only the library is wanted.
            dir.listDirectoryEntries().filter { it != library }.forEach { it.deleteIfExists() }
        }
    })
}

/**
 * Builds QuickJS as a wasm32-wasi module with zig, then writes it gzipped and in base64 as Kotlin source
 * for src@web. A string constant has a size limit, so the text is split into chunks that the loader joins.
 */
@OptIn(kotlin.io.path.ExperimentalPathApi::class)
@TaskAction
fun buildWasmModule(
    @Input nativeDir: Path,
    @Output wasmFile: Path,
    @Output sourcesDir: Path,
) {
    wasmFile.createParentDirectories()
    run(
        listOf(zig(), "cc", "-target", "wasm32-wasi", "-g0", "-s", "-o", wasmFile.toString(), "-mexec-model=reactor") +
            commonFlags(nativeDir) +
            listOf("-I$nativeDir", "-Wl,-z,stack-size=${wasmStackSize(nativeDir)}") +
            wasmExports(nativeDir).map { "-Wl,--export=$it" } +
            engineSources.map { nativeDir.resolve(it).toString() },
    )
    val gzipped = ByteArrayOutputStream().also { bytes ->
        GZIPOutputStream(bytes).use { it.write(wasmFile.readBytes()) }
    }.toByteArray()
    val chunks = Base64.getEncoder().encodeToString(gzipped).chunked(60_000).joinToString(",\n") { "    \"$it\"" }
    sourcesDir.deleteRecursively()
    sourcesDir.resolve("io/github/yuroyami/kitejs/quickjs/bridge/QuickJsWasm.kt").createParentDirectories().writeText(
        "/* Generated by the build from native/: QuickJS as WebAssembly, gzipped, in base64. */\n" +
            "package io.github.yuroyami.kitejs.quickjs.bridge\n\n" +
            "internal val QUICKJS_WASM: Array<String> = arrayOf(\n$chunks,\n)\n",
    )
}

/**
 * Compiles the C code for one Kotlin/Native target with the clang that Kotlin/Native ships (run_konan),
 * archives it as `libkitejs_quickjs.a`, and writes the cinterop definition that embeds it in the klib.
 * The definition is native/kitejs_quickjs.def plus the include and library paths of this build.
 */
@OptIn(kotlin.io.path.ExperimentalPathApi::class)
@TaskAction
fun buildKonanLibrary(
    konanTarget: String,
    kotlinVersion: String,
    @Input nativeDir: Path,
    @Output libraryDir: Path,
    @Output defFile: Path,
) {
    val runKonan = konanHome(kotlinVersion).resolve("bin/" + if (isWindows) "run_konan.bat" else "run_konan").toString()
    val objects = libraryDir.resolve("obj")
    libraryDir.deleteRecursively()
    objects.createDirectories()
    run(
        listOf(runKonan, "clang", "clang", konanTarget, "-c", "-fPIC") + commonFlags(nativeDir) +
            "-I$nativeDir" + engineSources.map { nativeDir.resolve(it).toString() },
        workDir = objects,
    )
    val library = libraryDir.resolve("libkitejs_quickjs.a")
    run(
        listOf(runKonan, "llvm", "llvm-ar", "rcs", library.toString()) +
            objects.listDirectoryEntries().filter { it.extension == "o" }.sortedBy { it.fileName.toString() }.map { it.toString() },
    )
    objects.deleteRecursively()
    // cinterop reruns only when the definition changes, so the definition names the library's checksum.
    val checksum = MessageDigest.getInstance("SHA-256").digest(library.readBytes()).joinToString("") { "%02x".format(it) }
    val template = nativeDir.resolve("kitejs_quickjs.def").readText().trimEnd()
    defFile.createParentDirectories().writeText(
        "$template\n" +
            "compilerOpts = -I${nativeDir.toString().replace('\\', '/')}\n" +
            "libraryPaths = ${libraryDir.toString().replace('\\', '/')}\n" +
            "# libkitejs_quickjs.a for $konanTarget, sha256 $checksum\n",
    )
}
